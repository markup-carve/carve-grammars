#!/usr/bin/env node
/*
 * Writes the TextMate rules that keep a list item inside a column-0 quote open
 * past its marker line (carve-grammars#881) into textmate/carve.tmLanguage.json.
 *
 *   node scripts/generate-quoted-item-rules.mjs          rewrite the generated entries
 *   node scripts/generate-quoted-item-rules.mjs --check  exit 1 when they are stale
 *
 * - `quoted_item_context` holds one zero-width begin/end rule per content width
 *   (the columns from the quote's space to the item's text). A back-reference
 *   cannot turn a marker into spaces, so each width is its own rule.
 * - Each width carries copies of the quoted code and comment fence rules whose
 *   end also fires on a quoted line left of the item's content column.
 * - `quoted_item_body` is the top-level pattern list without the context rule,
 *   which would otherwise re-enter itself at the same position.
 *
 * It must stay a begin/end rule: a `while` would make \G hold at every line
 * start, and `quoted_item_lazy_marker_line` reads \G as "the line right after".
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { grammarPath, valueSpan } from './generate-fence-languages.mjs';

const WIDTHS = { min: 2, max: 17 };
const INDENTS = 3;
const GAPS = 4;
const MARKER = '(?:[-*]|\\d{1,9}[.)]|(?:[a-zA-Z]|[ivxlcdm]+|[IVXLCDM]+)(?:\\)|\\.(?= {2})))';
const CODE_FENCE_END = '^(?![ \\t]*>\\2(?: |[ \\t]*$))|';

const clone = (value) => JSON.parse(JSON.stringify(value));

// The prefix of exactly `width` columns: indent, a marker run, then spaces.
function prefix(width) {
    const shapes = [];
    for (let indent = 0; indent <= INDENTS; indent++) {
        for (let gap = 1; gap <= GAPS; gap++) {
            const run = width - indent - gap;
            if (run >= 1) shapes.push(`${' '.repeat(indent)}[^ ]{${run}}${' '.repeat(gap)}`);
        }
    }

    return `(?:${shapes.join('|')})`;
}

// A code fence ends at the item before its closer is read; a comment fence's
// closer may sit left of the item, so it is read first (carve-js 0.1.16).
function itemFence(rule, width, closerFirst) {
    const out = clone(rule);
    delete out.comment;
    const itemEnd = `^(?=[ \\t]*>\\2 {1,${width}}[^ \\t\\n])`;
    out.end = closerFirst ? `${rule.end}|${itemEnd}` : `${itemEnd}|${rule.end}`;

    return out;
}

function context(width, codeFence, commentFence) {
    if (!codeFence.end.startsWith(CODE_FENCE_END)) throw new Error('quoted code fence end changed shape');

    return {
        begin: `^(?:\\A\\x{FEFF})?(?=(>)((?: >)*) (?= *${MARKER} +[^ \\t\\n])${prefix(width)}[^ \\t\\n])`,
        end: `^(?!\\G)(?!>\\2(?:[ \\t]*$| {${width + 1}}))`,
        patterns: [
            itemFence(codeFence, width, false),
            itemFence(commentFence, width, true),
            { include: '#quoted_item_body' },
        ],
    };
}

export function generate(grammar) {
    const repo = grammar.repository;
    const codeFence = repo.quoted_blocks.patterns.find((rule) => rule.end?.startsWith(CODE_FENCE_END));
    if (!codeFence) throw new Error('quoted code fence rule not found');
    const commentFence = repo.block_comment_on_quote_marker_line;
    const widths = [];
    for (let width = WIDTHS.min; width <= WIDTHS.max; width++) widths.push(context(width, codeFence, commentFence));

    return {
        quoted_item_context: {
            comment: 'A list item inside a column-0 quote keeps its content column past its marker line, so a fence in it ends with the item (carve-grammars#881). Generated by scripts/generate-quoted-item-rules.mjs.',
            patterns: widths,
        },
        quoted_item_body: {
            patterns: grammar.patterns.filter((rule) => rule.include !== '#quoted_item_context'),
        },
    };
}

export function splice(text, entries) {
    for (const [key, value] of Object.entries(entries)) {
        const span = valueSpan(text, key);
        const json = JSON.stringify(value);
        if (span) {
            text = text.slice(0, span[0]) + json + text.slice(span[1]);
        } else {
            const anchor = valueSpan(text, 'quoted_item_lazy_marker_line');
            text = `${text.slice(0, anchor[1])},\n    "${key}": ${json}${text.slice(anchor[1])}`;
        }
    }

    return text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const text = readFileSync(grammarPath, 'utf8');
    const next = splice(text, generate(JSON.parse(text)));
    JSON.parse(next);
    if (process.argv.includes('--check')) {
        if (next !== text) {
            console.error('textmate/carve.tmLanguage.json: generated quoted item rules are stale; run node scripts/generate-quoted-item-rules.mjs');
            process.exit(1);
        }
    } else {
        writeFileSync(grammarPath, next);
    }
}
